ALTER TABLE course
ADD COLUMN IF NOT EXISTS code TEXT;

CREATE TABLE IF NOT EXISTS course_item (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	course_id BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	modified_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	name TEXT NOT NULL,
	description TEXT,
	lecturer TEXT,
	tags TEXT[] NOT NULL DEFAULT '{}',
	start_at TIMESTAMP,
	end_at TIMESTAMP,
	kind TEXT NOT NULL,
	is_hidden BOOLEAN NOT NULL DEFAULT FALSE
);

DO $$
BEGIN
	IF NOT EXISTS (
		SELECT 1
		FROM pg_constraint
		WHERE conname = 'course_item_kind_check'
	) THEN
		ALTER TABLE course_item
		ADD CONSTRAINT course_item_kind_check CHECK (
			kind IN ('lecture', 'group', 'lab', 'seminarium')
		);
	END IF;
END
$$;

ALTER TABLE resource
ADD COLUMN IF NOT EXISTS course_item_id BIGINT;

DO $$
BEGIN
	IF NOT EXISTS (
		SELECT 1
		FROM pg_constraint
		WHERE conname = 'resource_course_item_id_fkey'
	) THEN
		ALTER TABLE resource
		ADD CONSTRAINT resource_course_item_id_fkey
			FOREIGN KEY (course_item_id)
			REFERENCES course_item(id)
			ON DELETE SET NULL;
	END IF;
END
$$;

CREATE INDEX IF NOT EXISTS resource_course_item_id_idx ON resource(course_item_id);
