/*
GOALS
- OCR many PDFs, store page text + token boxes for highlighting.
- Exact search via FTS (fast, ranked, scalable).
- Fuzzy search via pg_trgm (typos/partials).
- Custom processors (e.g. exam detector/parser) live in code, but their structured outputs are stored in DB with provenance.

WHY KEY CHOICES
- Page-first OCR (ocr_page): easy snippets + page hits + highlight retrieval.
- OCR attempts (ocr_attempt): A/B engines/settings and select one.
- Fuzzy is token-first (ocr_token trigram): scales better than trigram on long page texts.

Open option-questions
	1.	Fuzzy strategy
	•	Token-only trigram (default) vs also page-text trigram from day 1.
	•	Fuzzy as fallback only vs blended scoring with FTS.
	2.	Exam structured output shape
	•	Keep everything in output_json, or materialize hot fields into relational tables for speed:
	•	exam_meta(resource_id, date, course_code, max_points, ...)
	•	exam_question(resource_id, q_no, points, type, ...)
	•	exam_answer_key(...) JSONB is flexible; relational is faster for dashboards/filters.
	3.	Processor run uniqueness
	•	Should you enforce “only one succeeded run per (resource_id, processor_key, processor_version, params_json hash)”?
	•	If yes: add a deterministic params_hash and a partial unique index on succeeded.
	4.	Highlight precision
	•	Do you require char_start/char_end from day 1? (Strongly recommended.)
	•	If not, you’ll do heuristic mapping from matched strings → tokens (works, but noisier).
	5.	Partitioning
	•	When tokens reach tens/hundreds of millions, do you partition ocr_token by ocr_page_id range or by course_id (via resource join)?
	•	Not needed now, but worth designing for.

*/

CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Create immutable wrapper for unaccent (needed for generated columns)
CREATE OR REPLACE FUNCTION immutable_unaccent(text)
RETURNS text AS $$
  SELECT unaccent($1)
$$ LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT;

-- ----------------------------
-- Course / Resource / Pages
-- ----------------------------

CREATE TABLE course (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  code TEXT,
  description TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE course_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,

  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  modified_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

  name TEXT NOT NULL,
  description TEXT,
  lecturer TEXT,
  tags TEXT[] NOT NULL DEFAULT '{}',

  start_at TIMESTAMP,
  end_at TIMESTAMP,

  kind TEXT NOT NULL,
  is_hidden BOOLEAN NOT NULL DEFAULT FALSE,

  CHECK (kind IN ('lecture', 'group', 'lab', 'seminarium', 'examination'))
);
-- status: pending, uploaded, ocr_running, searchable, archived
CREATE TABLE resource (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

  course_id BIGINT REFERENCES course(id) ON DELETE CASCADE,
  course_item_id BIGINT REFERENCES course_item(id) ON DELETE SET NULL,
  parent_resource_id BIGINT REFERENCES resource(id) ON DELETE SET NULL,

  derived_from_id BIGINT REFERENCES resource(id) ON DELETE SET NULL,
  extraction_target_resource_id BIGINT REFERENCES resource(id) ON DELETE SET NULL,

  name TEXT NOT NULL,
  description TEXT,
  mime_type TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',

  storage_filename TEXT,
  storage_key TEXT,
  storage_size BIGINT,
  storage_sha256 TEXT
);

CREATE TABLE resource_page (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource_id BIGINT NOT NULL REFERENCES resource(id) ON DELETE CASCADE,

  page_number INT NOT NULL, -- 1-based
  width_px INT,
  height_px INT,

  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

  CHECK (page_number > 0),
  UNIQUE (resource_id, page_number)
);

-- ----------------------------
-- OCR Attempts
-- ----------------------------

CREATE TABLE ocr_attempt (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

  resource_id BIGINT NOT NULL REFERENCES resource(id) ON DELETE CASCADE,

  ocr_engine TEXT NOT NULL,
  engine_version TEXT,
  processing_time_ms BIGINT,

  eval_group TEXT,
  quality_score DOUBLE PRECISION,
  manual_rating SMALLINT,

  selected BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE UNIQUE INDEX ocr_attempt_one_selected_per_resource
  ON ocr_attempt(resource_id)
  WHERE selected = TRUE;

-- ----------------------------
-- OCR per page (EXACT SEARCH lives here)
-- ----------------------------

CREATE TABLE ocr_page (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ocr_attempt_id BIGINT NOT NULL REFERENCES ocr_attempt(id) ON DELETE CASCADE,
  resource_page_id BIGINT NOT NULL REFERENCES resource_page(id) ON DELETE CASCADE,

  content TEXT NOT NULL,

  width_px INT NOT NULL,
  height_px INT NOT NULL,
  unit TEXT NOT NULL DEFAULT 'px',

  -- normalize once to improve both FTS and fuzzy matching (diacritics etc)
  content_unaccent TEXT GENERATED ALWAYS AS (immutable_unaccent(coalesce(content, ''))) STORED,

  -- exact search (ranked)
  tsv_en tsvector GENERATED ALWAYS AS (
    to_tsvector('english', immutable_unaccent(coalesce(content, '')))
  ) STORED,
  tsv_sv tsvector GENERATED ALWAYS AS (
    to_tsvector('swedish', immutable_unaccent(coalesce(content, '')))
  ) STORED,

  UNIQUE (ocr_attempt_id, resource_page_id)
);

-- ----------------------------
-- Tokens (HIGHLIGHT geometry + FUZZY SEARCH lives here)
-- ----------------------------

CREATE TABLE ocr_token (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ocr_page_id BIGINT NOT NULL REFERENCES ocr_page(id) ON DELETE CASCADE,

  token_index INT NOT NULL,
  text TEXT NOT NULL,
  text_unaccent TEXT GENERATED ALWAYS AS (immutable_unaccent(coalesce(text,''))) STORED,

  conf DOUBLE PRECISION,

  x0 INT NOT NULL, y0 INT NOT NULL, x1 INT NOT NULL, y1 INT NOT NULL,

  -- recommended: enables precise mapping from text spans -> tokens
  char_start INT,
  char_end INT,

  CHECK (token_index >= 0),
  CHECK (x0 <= x1 AND y0 <= y1)
);

-- ----------------------------
-- Processor runs (definitions in code, outputs in DB)
-- ----------------------------

/*
Use cases:
- exam detector: outputs JSON like {is_exam:true, confidence:..., signals:[...]}
- exam parser: outputs JSON like {exam:{...}, questions:[...], grading:[...], ...}
- any future pipeline step can write JSONB.

We store:
- processor_key: stable identifier in code ("exam.detector", "exam.parser.gu")
- processor_version: code version/semver/git sha to reproduce results
- input refs: which OCR attempt (if any) it used, and optional derived artifacts
*/
CREATE TABLE processing_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

  resource_id BIGINT NOT NULL REFERENCES resource(id) ON DELETE CASCADE,

  processor_key TEXT NOT NULL,
  processor_version TEXT,

  status TEXT NOT NULL DEFAULT 'pending', -- pending,running,succeeded,failed
  error TEXT,

  -- If the processor used OCR output, pin it for reproducibility
  ocr_attempt_id BIGINT REFERENCES ocr_attempt(id) ON DELETE SET NULL,

  -- Parameters used for the run (thresholds, model names, rulesets)
  params_json JSONB,

  -- Structured output (the real payload you care about)
  output_json JSONB,

  -- Optional derived artifact (e.g. normalized PDF, question crops, alt OCR json file)
  derived_resource_id BIGINT REFERENCES resource(id) ON DELETE SET NULL
);

